package lexer;

/**
 * Перелік типів токенів, які породжує {@link Lexer}.
 *
 * <p>Ключові слова розпізнаються за <b>основами</b> (див. таблицю в
 * {@link Lexer}), тому один тип може відповідати кільком морфологічним
 * формам: {@code ТОЧКА}, {@code ТОЧКИ}, {@code ТОЧОК} — усе {@link #POINT}.
 * Окремий тип {@link #POINT_LOC} для словоформи {@code ТОЧЦІ} дозволяє
 * розрізнити «точка» (оголошення) і «в точці» (місце для перпендикуляра).
 *
 * <p>Типи {@link #IDENTIFIER} і {@link #NUMBER} — «листки» мови; решта —
 * службові слова й пунктуація.
 */
public enum TokenType {
    /** Оголошення точки: {@code ТОЧКА}, {@code ТОЧКИ}, {@code ТОЧОК}. */
    POINT,
    /** Локатив «в точці»: {@code ТОЧЦІ}. */
    POINT_LOC,
    /** Слово «пряма» у будь-якому відмінку: {@code ПРЯМА}, {@code ПРЯМУ}, {@code ПРЯМОЇ}. */
    LINE,
    /** {@code ЧЕРЕЗ} — прийменник у «ПРОВЕСТИ ПРЯМУ ЧЕРЕЗ …». */
    THROUGH,
    /** {@code ПРОВЕСТИ} — дієслово «провести». */
    DRAW,
    /** {@code ПОБУДУВАТИ} — дієслово «побудувати». */
    BUILD,
    /** {@code ПЕРПЕНДИКУЛЯР} у будь-якому відмінку. */
    PERPENDICULAR,
    /** {@code ДО} — прийменник «до». */
    TO,
    /** {@code В} — прийменник «в». */
    AT,
    /** {@code ТРИКУТНИК} у будь-якому відмінку. */
    TRIANGLE,
    /** {@code ПО} — прийменник «по». */
    BY,
    /** {@code ТРЬОМ} — числівник «трьом». */
    THREE,
    /** {@code ВЕРШИНА}, {@code ВЕРШИНАМ} — «вершина». */
    VERTEX,
    /** {@code ВІДРІЗОК} у будь-якому відмінку. */
    SEGMENT,
    /** {@code ВІД} — прийменник «від». */
    FROM,
    /** Ім'я, що складається лише з латинських літер; несе код у {@link Token#code()}. */
    IDENTIFIER,
    /** Число: ціле або дробове, з опціональним знаком. */
    NUMBER,
    /** Кома {@code ,}. */
    COMMA,
    /** Відкривальна дужка {@code (}. */
    LPAREN,
    /** Закривальна дужка {@code )}. */
    RPAREN,
    /** Крапка з комою {@code ;} — розділювач речень. */
    SEMICOLON,
    /** Символ {@code #} — кінець тексту. */
    END,
    /** Кінець потоку токенів. */
    EOF
}
